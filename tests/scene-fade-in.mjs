import assert from 'node:assert/strict';
import path from 'node:path';
import { build } from 'esbuild';

const result = await build({ stdin: { resolveDir: process.cwd(), contents: `export * from './src/renderer/frontend/src/utils/createSceneFadeIn'; export * from './src/shared/events/eventAttention'; export * from './src/renderer/frontend/src/components/events/eventWarningMessage';` }, bundle: true, write: false, format: 'esm', platform: 'node', alias: { '@': path.resolve('src/renderer/frontend/src') } });
const { createSceneFadeIn, reconcileSceneFadeIn, countSceneAttention, eventWarningMessage } = await import(`data:text/javascript;base64,${Buffer.from(result.outputFiles[0].text).toString('base64')}`);
const fade = createSceneFadeIn();
assert.equal(fade.command, 'EVENT_FADE_IN');
assert.equal(fade.args.__comment, false);
assert.equal(fade.args.__automatic, true);
assert.equal(fade.args.speed, 2);
assert.notEqual(fade.id, createSceneFadeIn().id);
assert.equal(countSceneAttention({ script: [fade] }), 0, 'New scenes start with an active Fade In without warnings');
assert.equal(countSceneAttention({ script: [{ ...fade, args: { ...fade.args, __comment: true } }] }), 1, 'A sole commented Fade In warns because none is enabled');
assert.equal(countSceneAttention({ script: [{ id: 'wait', command: 'EVENT_WAIT', args: { __comment: true } }] }), 0, 'Other commented events remain intentional');
const wait = { id: 'wait', command: 'EVENT_WAIT', args: { frames: 10 } };
const manual = { id: 'manual', command: 'EVENT_FADE_IN', args: { speed: 5 } };
const replaced = reconcileSceneFadeIn([fade, wait], [fade, wait, manual]);
assert.deepEqual(replaced, [fade, wait, manual], 'Adding a Fade In preserves the first automatic and the order of all events');
assert.equal(replaced[0].args.speed, 2);
assert.equal(replaced[2].args.speed, 5);
const restored = reconcileSceneFadeIn(replaced, [wait]);
assert.equal(restored[0].command, 'EVENT_FADE_IN');
assert.equal(restored[0].args.__automatic, true);
assert.equal(restored[0].args.__comment, false);
assert.equal(restored[1], wait);
assert.equal(countSceneAttention({ script: restored }), 0, 'Deletion restores an active default, not a missing-fade warning');
assert.equal(reconcileSceneFadeIn(restored, restored), restored, 'Ordinary edits preserve the automatic event ID');
assert.deepEqual(reconcileSceneFadeIn([manual], [{ ...manual, args: { ...manual.args, __comment: true } }])[0].args.__comment, true, 'Commenting a manual fade does not replace it');
assert.equal(reconcileSceneFadeIn([manual, { ...manual, id: 'second' }], [{ ...manual, id: 'second' }])[0].args.__automatic, true, 'Deleting the first fade promotes the next one');
const commented = { ...manual, args: { ...manual.args, __comment: true } };
const multiple = reconcileSceneFadeIn([fade], [commented, wait, fade]);
assert.deepEqual(multiple.map(event => event.id), [manual.id, wait.id, fade.id], 'Recognition never moves events');
assert.equal(multiple[0].args.__automatic, true, 'The first Fade In owns the role even when commented');
assert.equal(multiple[0].args.__comment, true, 'Recognition preserves the comment');
assert.equal(multiple[2].args.__automatic, undefined, 'Later fades lose the automatic marker');
assert.equal(countSceneAttention({ script: multiple }), 0, 'Multiple fades, including commented fades, have no warning');
for (const event of multiple) assert.equal(eventWarningMessage(event, key => key, multiple), '', 'The event row has no warning tooltip for intentional fades');
const moved = reconcileSceneFadeIn(multiple, [multiple[2], multiple[0], wait]);
assert.equal(moved[0].args.__automatic, true, 'Reordering transfers the automatic role');
assert.equal(moved[1].args.__automatic, undefined);
assert.equal(countSceneAttention({ script: moved }), 0);
const allDisabled = multiple.map(event => event.command === 'EVENT_FADE_IN' ? { ...event, args: { ...event.args, __comment: true } } : event);
assert.equal(countSceneAttention({ script: allDisabled }), 1, 'All commented fades produce one hierarchy warning');
assert.match(eventWarningMessage(allDisabled[0], key => key, allDisabled), /events.fadeIn.disabled/);
assert.equal(eventWarningMessage(allDisabled[2], key => key, allDisabled), '', 'The second disabled fade has no badge');
const enabledSecond = allDisabled.map((event, index) => index === 2 ? { ...event, args: { ...event.args, __comment: false } } : event);
assert.equal(countSceneAttention({ script: enabledSecond }), 0, 'Enabling a later fade clears the first warning');
assert.equal(eventWarningMessage(enabledSecond[0], key => key, enabledSecond), '');
console.log('Scene Fade In: first-event recognition, multiple fades and intentional comments passed.');
