import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle=await build({stdin:{contents:"export * from './src/shared/events/backgroundCompatibility.ts'; export * from './src/shared/events/eventAttention.ts'; export * from './src/renderer/frontend/src/i18n/eventPicker.ts';",resolveDir:process.cwd()},bundle:true,write:false,format:'esm',platform:'node'});
const {validateBackgroundCompatibility,applyBackgroundCompatibility,countEventAttention,eventPickerCatalogs}=await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
for(const [language,catalog] of Object.entries(eventPickerCatalogs)) for(const [key,value] of Object.entries(catalog)) {
  if(key.startsWith('events.bgAnimation.') || key.startsWith('events.bgCompatibility.') || key.startsWith('events.wait.')) assert.ok(!/[?\uFFFD]/.test(value),`${language}/${key}: corrupted translated characters`);
}
const event=(id,command,args={})=>({id,command,args});
const transform=event('scale','EVENT_BACKGROUND_SET_SCALE',{layerId:0});
const change=event('change','EVENT_CHANGE_LAYER',{layerId:0,backgroundId:'small'});
const base={id:'scene',name:'Example',sceneType:'Top Down',backgrounds:[{layerId:0,backgroundId:'large'}],script:[transform,change]};
const images=[{id:'large',name:'Large'},{id:'small',name:'Small'}];
let inspected=0;
const inspect=async(s,l,image)=>{inspected++;return image.id==='large'?331:16;};
let results=await validateBackgroundCompatibility([base],[],images,inspect);
assert.equal(results.get('scale').issues[0].count,331);
assert.deepEqual(results.get('change'),{affine:true,count:16,image:'Small',issues:[]});
const warned=applyBackgroundCompatibility(base,results);
assert.equal(countEventAttention(warned.script),1);
assert.equal(applyBackgroundCompatibility(warned,results),warned,'Validation must preserve unchanged references');
const repaired={...warned,backgrounds:[{layerId:0,backgroundId:'small'}]};
results=await validateBackgroundCompatibility([repaired],[],images,inspect);
assert.equal(countEventAttention(applyBackgroundCompatibility(repaired,results).script),0);
const swapped={...base,script:[transform,{...change,args:{layerId:0,backgroundId:'large'}}],backgrounds:[{layerId:0,backgroundId:'small'}]};
results=await validateBackgroundCompatibility([swapped],[],images,inspect);
assert.equal(results.get('scale').issues[0].image,'Large');
assert.equal(results.get('change').issues[0].count,331);
const shared={id:'shared',events:[transform,event('cycle','EVENT_CALL_SCRIPT',{scriptId:'shared'})]};
const branched={...base,script:[],actors:[{script:[{...event('if','EVENT_IF'),children:{then:[event('call','EVENT_CALL_SCRIPT',{scriptId:'shared'})]}}]}]};
results=await validateBackgroundCompatibility([branched],[shared],images,inspect);
assert.equal(results.get('scale').issues[0].count,331);
results=await validateBackgroundCompatibility([{...base,script:[{...transform,args:{layerId:0,__comment:true}},change]}],[],images,inspect);
assert.equal(results.size,0,'Disabled transformations must not require affine conversion');
assert.equal(applyBackgroundCompatibility(warned,results).script[0].args.__backgroundCompatibility,undefined);
inspected=0;
results=await validateBackgroundCompatibility([{...base,sceneType:'POINTNCLICK'}],[],images,inspect);
assert.equal(inspected,0);assert.equal(results.get('scale').affine,false);
results=await validateBackgroundCompatibility([{...base,backgrounds:[],script:[transform]}],[],images,inspect);
assert.deepEqual(results.get('scale').issues,[],'Empty backgrounds are accepted by the build and should not warn');
results=await validateBackgroundCompatibility([{...base,backgrounds:[{layerId:0,backgroundId:'deleted'}]}],[],images,inspect);
assert.equal(results.get('scale').issues[0].code,'missing');
results=await validateBackgroundCompatibility([base],[],images,async()=>{throw Error('unavailable');});
assert.equal(results.get('scale').issues[0].code,'unreadable');
const crowded={...base,backgrounds:[0,1,2,3].map(layerId=>({layerId,backgroundId:'small'}))};
results=await validateBackgroundCompatibility([crowded],[],images,inspect);
assert.equal(results.get('scale').issues[0].code,'layers');
assert.equal(results.get('change').issues[0].code,'layers');
const sheet={id:'sheet',name:'HD sheet',hd:true,imageWidth:480,imageHeight:160};
const animate=event('sheet-animation','EVENT_BACKGROUND_ANIMATE',{backgroundId:'sheet',layerId:0});
const sheetScene={...base,backgrounds:[{layerId:0,backgroundId:'small'}],script:[animate]};
const inspectFrame=async(scene,layer,image,replacement,args,affine)=>image.id==='sheet'?300:16;
results=await validateBackgroundCompatibility([sheetScene],[],[...images,sheet],inspectFrame);
assert.equal(results.get('sheet-animation').count,300);
assert.equal(results.get('sheet-animation').issues.length,0,'Regular frames use the 1024-tile limit');
results=await validateBackgroundCompatibility([{...sheetScene,script:[animate,transform]}],[],[...images,sheet],inspectFrame);
assert.equal(results.get('sheet-animation').issues[0].code,'tiles');
assert.equal(results.get('scale').issues[0].count,300,'Affine transformations must also validate frames loaded by an animation event');
results=await validateBackgroundCompatibility([{...sheetScene,sceneType:'Logo'}],[],[...images,sheet],async()=>0);
assert.equal(results.get('sheet-animation').issues.length,0);
results=await validateBackgroundCompatibility([{...sheetScene,sceneType:'Logo'}],[],[...images,sheet],async()=>{throw Error('Missing bitmap source');});
assert.equal(results.get('sheet-animation').issues[0].code,'geometry');
results=await validateBackgroundCompatibility([{...sheetScene,script:[{...animate,args:{...animate.args,frameCount:3}}]}],[],[...images,sheet],inspectFrame);
assert.equal(results.get('sheet-animation').issues[0].code,'geometry');
console.log('Background compatibility passed: initial and replacement images, shared scripts and branches, hardware layers, bitmap bypass, empty layers, unavailable assets and warning repair.');
