import assert from 'node:assert/strict';
import { calculateSceneSpriteBudget, spriteObjectCount } from '../dist/shared/sceneSpriteBudget.js';
import { createSpriteCanvasPlan } from '../dist/main/utils/builders/spriteCanvasPlan.js';

const ids = ['2f591f1d-270c-40ec-89c0-9f925ab68f23','0aa307ad-7329-4599-bc39-8f8c909f6dcb','0e061a11-74e7-4848-a95b-fc25f5683cee','54897b71-abac-4e4b-9cf2-e9ac7d6f420e','91487fda-588f-4276-9629-f1d92f1ea24a','0265a5f1-b33c-450d-88a8-aa3d353de808','1f6579b7-ce2d-455f-a4c6-794973c81c71','a6d52c5f-bc31-4080-86a5-3e1bf92d9068','1a58c41f-2505-47fd-933b-acf97dd715c5','35bbc69f-7475-4717-8ba9-749d22bf67b0'];
const [sceneId,spriteId,prefabId,actorId,scriptId,otherPrefabId] = ids;
const sprite = { id: spriteId, playerFrameWidth:16,playerFrameHeight:16,imageWidth:16,imageHeight:16 };
const prefab = {id:prefabId,type:'actor',actor:{id:actorId,spriteId}};
let serial=6;
const event=(command,args={},children)=>({id:ids[serial++%ids.length],version:1,command,args,...(children?{children}:{})});
const spawn=()=>event('EVENT_SPAWN_ACTOR',{source:'prefab',prefabId});
const remove=()=>event('EVENT_REMOVE_ACTOR',{source:'prefab',prefabId});
const options={sprites:[sprite],prefabs:[prefab],scripts:[],playerSpriteId:spriteId};
const budget=(script=[],extra={},opts={})=>calculateSceneSpriteBudget({id:sceneId,actors:[],triggers:[],script,...extra},{...options,...opts});
assert.equal(budget([],{}, {hasPlayer:true}).peakSprites,1);
assert.equal(budget([], {actors:[{id:actorId,spriteId}]}).peakSprites,1);
assert.equal(budget([spawn(),spawn(),spawn()]).peakSprites,3);
assert.equal(budget([spawn(),remove(),spawn()]).peakSprites,1);
assert.equal(budget([spawn(),event('EVENT_ACTOR_HIDE_ALL'),spawn()]).peakSprites,2,'hiding does not free OAM');
assert.equal(budget([event('EVENT_SPAWN_ACTOR',{actorId}),event('EVENT_ACTOR_SPAWN',{actorId})],{actors:[{id:actorId,spriteId}]}).peakSprites,1,'placed actors are singleton identities');
assert.equal(budget([{...spawn(),args:{...spawn().args,__comment:true}}]).peakSprites,0);
const loop=event('EVENT_FOR',{start:0,end:31,step:1},{then:[spawn()]});
assert.equal(budget([loop]).peakSprites,32);
assert.equal(budget([loop]).prefabCapacities[prefabId],32);
assert.equal(budget([event('EVENT_FOR',{start:0,end:199,step:1},{then:[spawn()]})]).peakSprites,200);
assert.equal(budget([event('EVENT_FOR',{start:0,end:99,step:1},{then:[spawn(),event('EVENT_BREAK')]})]).peakSprites,1);
assert.equal(budget([event('EVENT_WHILE',{left:0,operator:'==',right:1},{then:[spawn()]})]).peakSprites,0);
assert.equal(budget([event('EVENT_IF',{left:0,operator:'==',right:1},{then:[spawn()],else:[]})]).peakSprites,0);
assert.ok(budget([event('EVENT_WAIT_FOR_BUTTON',{buttons:['A']},{then:[spawn()]})]).unbounded);
assert.equal(budget([event('EVENT_FOR',{start:0,end:127,step:1},{then:[spawn(),remove()]})]).peakSprites,1);
const recurring={actors:[{id:actorId,spriteId,onUpdateScript:[spawn()]}]};
const accumulating=budget([],recurring);assert.ok(accumulating.peakSprites>128&&accumulating.unbounded);assert.equal(accumulating.prefabCapacities[prefabId],128);
assert.equal(budget([],{actors:[{id:actorId,spriteId,onUpdateScript:[spawn(),remove()]}]}).peakSprites,2);
assert.equal(budget([event('EVENT_CALL_SCRIPT',{scriptId}),event('EVENT_CALL_SCRIPT',{scriptId})],{}, {scripts:[{id:scriptId,events:[spawn()]}]}).peakSprites,2);
const recursiveCall=event('EVENT_CALL_SCRIPT',{scriptId});
assert.ok(budget([recursiveCall],{}, {scripts:[{id:scriptId,events:[spawn(),recursiveCall]}]}).unbounded);
const balancedRecursion=budget([recursiveCall],{}, {scripts:[{id:scriptId,events:[spawn(),remove(),recursiveCall]}]});
assert.equal(balancedRecursion.peakSprites,1);assert.equal(balancedRecursion.unbounded,false);
const other={id:otherPrefabId,type:'actor',actor:{id:actorId,spriteId}};
const branches=event('EVENT_IF',{}, {then:[spawn()],else:[event('EVENT_SPAWN_ACTOR',{source:'prefab',prefabId:otherPrefabId})]});
assert.equal(budget([branches],{}, {prefabs:[prefab,other]}).peakSprites,1,'alternative branches are not simultaneous');
assert.equal(budget([],{triggers:[{id:actorId,once:true,onEnterScript:[spawn()]}]}).peakSprites,1);
assert.ok(budget([],{triggers:[{id:actorId,onEnterScript:[spawn()]}]}).unbounded);
assert.equal(budget([spawn()],{}, {prefabs:[{...prefab,actor:{...prefab.actor,onInitScript:[event('EVENT_REMOVE_ACTOR',{actorId:'__SELF__'})]}}]}).peakSprites,1);
assert.equal(budget([spawn()],{}, {prefabs:[{...prefab,actor:{...prefab.actor,onInitScript:[event('EVENT_REMOVE_ACTOR',{actorId})]}}]}).peakSprites,1);
assert.equal(budget([event('EVENT_CHANGE_SCENE',{sceneId}),spawn()]).peakSprites,0);
for(const [width,height] of [[8,8],[16,16],[64,64],[96,64],[128,64],[128,128]]) {
 const resource={...sprite,playerFrameWidth:width,playerFrameHeight:height,imageWidth:width,imageHeight:height};
 const plan=createSpriteCanvasPlan(resource,width,height);
 assert.equal(spriteObjectCount(resource),plan.partsColumns*plan.partsRows);
}
const composed={...sprite,playerFrameWidth:128,playerFrameHeight:64};
assert.equal(budget([spawn(),spawn()],{}, {sprites:[composed]}).peakSprites,4);
const animated={...sprite,playerAnimationStates:[{id:actorId,animations:[{id:scriptId,frames:Array(64).fill(0)}]}]};
assert.equal(spriteObjectCount(animated),1,'64 animation frames occupy a single hardware object');
console.log('Scene sprite budget passed: player, composite packing, animation frames, persistent spawns, despawn peaks, repeat loops, triggers, reusable calls, branches, Self, comments and scene changes.');
