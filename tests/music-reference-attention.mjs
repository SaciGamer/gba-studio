import assert from 'node:assert/strict';
import { build } from 'esbuild';
const result = await build({ stdin: { resolveDir: process.cwd(), contents: "export * from './src/shared/events/sceneReferenceCleanup'; export * from './src/shared/events/eventAttention';" }, bundle: true, write: false, platform: 'node', format: 'esm' });
const { clearMissingEventReferences, countSceneAttention, countScriptAttention, countPrefabAttention } = await import('data:text/javascript;base64,' + Buffer.from(result.outputFiles[0].text).toString('base64'));
const empty = new Set();
const available = { scenes: empty, actors: empty, triggers: empty, scripts: empty, variables: empty, music: new Set(['original', 'tracker-id']) };
const music = (id, musicId) => ({ id, command: 'EVENT_PLAY_MUSIC', args: { musicId } });
const scene = { script: [music('valid', 'original')], actors: [{ onInitScript: [music('missing', 'deleted-song')] }] };
const repaired = clearMissingEventReferences(scene, available);
assert.equal(repaired.changed, true);
assert.equal(countSceneAttention(repaired.value), 1);
assert.equal(repaired.value.actors[0].onInitScript[0].args.musicId, undefined);
assert.equal(scene.actors[0].onInitScript[0].args.musicId, 'deleted-song');
const script = { events: [music('valid', 'tracker-id')], eventGraphs: { init: { nodes: [music('graph', 'missing')] } } };
assert.equal(countScriptAttention(clearMissingEventReferences(script, available).value), 1);
const prefab = { type: 'trigger', trigger: { onEnterScript: [music('prefab', 'missing')] } };
assert.equal(countPrefabAttention(clearMissingEventReferences(prefab, available).value), 1);
assert.equal(clearMissingEventReferences(script, { ...available, music: undefined }).changed, false, 'An unavailable catalog must not clear references');
assert.equal(clearMissingEventReferences({ events: [music('valid', 'tracker-id')] }, available).changed, false);
console.log('Missing music references propagate to scene, script and prefab attention: passed');
