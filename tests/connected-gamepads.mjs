import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import ts from 'typescript';
const source = fs.readFileSync('src/renderer/frontend/src/utils/connectedGamepads.ts', 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const context = { exports: {} };
vm.runInNewContext(compiled, context);
const target = new EventTarget();
Object.assign(target, { document: new EventTarget(), setInterval: callback => { target.poll = callback; return 1; }, clearInterval: () => { target.cleared = true; } });
const xbox = { index: 2, id: 'Xbox 360 Controller', connected: true };
const other = { index: 0, id: 'Other controller', connected: true };
let pads = [null, null, xbox];
const changes = [];
const stop = context.exports.watchConnectedGamepads(target, { getGamepads: () => pads }, found => changes.push(Array.from(found)));
assert.deepEqual(changes.at(-1), [xbox]);
const dispatch = (type, gamepad) => { const event = new Event(type); event.gamepad = gamepad; target.dispatchEvent(event); };
dispatch('gamepadconnected', other);
assert.deepEqual(changes.at(-1), [other, xbox]);
pads = [other, null, xbox]; target.poll();
assert.deepEqual(changes.at(-1), [other, xbox]);
dispatch('gamepaddisconnected', xbox);
assert.deepEqual(changes.at(-1), [other]);
pads = []; target.dispatchEvent(new Event('focus'));
assert.deepEqual(changes.at(-1), []);
pads = [null, null, xbox]; target.document.dispatchEvent(new Event('visibilitychange'));
assert.deepEqual(changes.at(-1), [xbox]);
stop(); assert.equal(target.cleared, true);
const count = changes.length;
dispatch('gamepadconnected', other); target.dispatchEvent(new Event('focus'));
target.document.dispatchEvent(new Event('visibilitychange'));
assert.equal(changes.length, count);
console.log('Gamepad detection: preconnected device, events, sparse indices, focus, visibility and cleanup passed.');
