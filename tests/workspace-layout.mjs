import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({ entryPoints: ['src/renderer/frontend/src/utils/workspaceLayout.ts'], bundle: true, write: false, platform: 'node', format: 'esm' });
const { restoreLeftNavigation, loadWorkspaceLayout, cachedWorkspaceLayout, workspaceLayoutKey, cacheLeftNavigation, cacheWorkspaceLayout } = await import('data:text/javascript;base64,' + Buffer.from(bundle.outputFiles[0].text).toString('base64'));
const calls = []; const pending = new Map();
globalThis.window = { innerHeight: 640, electronAPI: { loadLastPositionSplitters: key => { calls.push(key); return new Promise(resolve => pending.set(key, resolve)); } } };
const saved = { sizes: [300, 40, 180, 120], sections: { scenes: true, prefabs: false, scripts: true, variables: true }, expandedKeys: { scenes: ['scene'], prefabs: [], scripts: [], variables: [] } };
assert.deepEqual(restoreLeftNavigation(saved, 640).sizes, saved.sizes, 'restoring unchanged geometry must not drift');
assert.deepEqual(restoreLeftNavigation(undefined, 640).sizes, [160, 160, 160, 160], 'default has four sections');
const resized = restoreLeftNavigation(saved, 940);
assert.deepEqual(resized.sizes, [450, 40, 270, 180]);
const invalid = restoreLeftNavigation({ sizes: [NaN, -5, Infinity, 0], sections: { scenes: false, prefabs: false, scripts: false, variables: false }, expandedKeys: { scenes: ['scene', 12, null, {}] } }, 640);
assert.equal(invalid.sections.scenes, true); assert.deepEqual(invalid.expandedKeys.scenes, ['scene', 12]);
assert.equal(invalid.sizes.reduce((a,b)=>a+b), 640);
assert.ok(restoreLeftNavigation({ sizes: [1, 10000, 1, 1] }, 640).sizes.every(size => size > 40), 'tiny saved weights must not collapse open sections');
assert.equal(workspaceLayoutKey('E:\\Game\\Project.gbaproj'), workspaceLayoutKey('e:/game/project.gbaproj'));
const first = loadWorkspaceLayout('project-a'), shared = loadWorkspaceLayout('project-a');
assert.equal(first, shared, 'preload and navigation share one IPC request');
await Promise.resolve();
pending.get(workspaceLayoutKey('project-a'))({ main: [280, 700, 365], leftNavigation: saved });
await first;
assert.deepEqual(cachedWorkspaceLayout('project-a').leftNavigation, saved);
await loadWorkspaceLayout('project-a'); assert.equal(calls.length, 1);
cacheLeftNavigation('project-a', { ...saved, sections: { ...saved.sections, scripts: false } });
assert.equal(cachedWorkspaceLayout('project-a').leftNavigation.sections.scripts, false);
assert.deepEqual(cachedWorkspaceLayout('project-a').main, [280, 700, 365]);
assert.equal(cachedWorkspaceLayout('project-b'), undefined, 'different projects must not share layout');
cacheLeftNavigation('project-b', { sections: { scripts: true } });
cacheWorkspaceLayout('project-b', { main: [320, 600, 365] });
assert.deepEqual(cachedWorkspaceLayout('project-a').main, [320, 600, 365], 'shared splitter widths remain current across projects');
assert.equal(cachedWorkspaceLayout('project-a').leftNavigation.sections.scripts, false, 'shared widths must not overwrite project navigation');
console.log('Workspace layout: preload deduplication, cached remount, project isolation, four-panel defaults, size ratios, minimums and invalid preferences passed.');
