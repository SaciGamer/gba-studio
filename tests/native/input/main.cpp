    input.clear_button_actions("LEFT");
    if(input.held("RIGHT") || input.pressed("RIGHT")) return 41;
    input.queue_default_action("LEFT", "LEFT");
    input.poll();
    if(!input.held("LEFT") || input.held("RIGHT")) return 42;
    input.queue_default_action("B", "LEFT");
    input.queue_default_action("RIGHT", "A");
    input.queue_default_action("RIGHT");
    input.clear_button_actions("LEFT");
    input.poll();
