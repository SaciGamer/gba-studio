    if(!input.pressed("confirm")) return 55;
    input.set_scene_type("Logo");
    if(input.pressed("confirm")) return 56;
    input.set_scene_type("Platform");
    if(!input.pressed("confirm")) return 57;
    input.configure_scene_maps(nullptr, 0);
    input.set_scene_type(nullptr);
    if(input.pressed("confirm")) return 58;
