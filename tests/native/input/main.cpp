    if(! input.pressed("move_left") || ! input.held("move_left")) return 14;
    if(! input.pressed("A")) return 11;
    input.clear_overrides();
    bn::keypad::b_pressed_state = false;
    bn::keypad::left_pressed_state = false;
    bn::keypad::start_pressed_state = false;
    bn::keypad::a_pressed_state = true;
    input.set_override("B", true);
    if(!input.queue_default_action("B", "A")) return 30;
    input.poll();
    if(!input.pressed("jump") || !input.held("jump") || input.binding_pressed("B")) return 31;
    input.poll();
    if(input.pressed("jump") || !input.held("jump")) return 32;
    bn::keypad::a_pressed_state = false;input.poll();
