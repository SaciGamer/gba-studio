    input.clear_overrides();
    bn::keypad::a_pressed_state = false;
    bn::keypad::left_pressed_state = true;
    bn::keypad::right_pressed_state = false;
    input.set_override("LEFT", true);
    input.set_override("RIGHT", true);
    input.queue_default_action("RIGHT", "LEFT");
    input.poll();
