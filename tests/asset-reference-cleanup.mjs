import assert from 'node:assert/strict';
import { build } from 'esbuild';

const load = async file => {
  const bundle = await build({ entryPoints: [file], bundle: true, write: false, format: 'esm', platform: 'node' });
  return import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
};
const { clearMissingAssetReferences, clearMissingEventReferences, hasAssetReferenceWarning, countAssetReferenceAttention } = await load('src/shared/events/sceneReferenceCleanup.ts');
const { countSceneAttention, countPrefabAttention } = await load('src/shared/events/eventAttention.ts');
const { normalizeSceneResource } = await load('src/shared/sceneResource.ts');
const available = { backgrounds: new Set(['valid-bg']), sprites: new Set(['valid-sprite']) };
const source = { backgrounds: [{ layerId: 0, backgroundId: 'deleted-bg', tileMap: [[1]], autoTileMap: [[2]] }, { layerId: 1, backgroundId: null }], actors: [{ id: 'actor', spriteId: 'deleted-sprite' }] };
const result = clearMissingAssetReferences(source, available);
assert.equal(result.changed, true);
assert.equal(source.backgrounds[0].backgroundId, 'deleted-bg');
assert.equal(result.value.backgrounds[0].backgroundId, null);
assert.deepEqual(result.value.backgrounds[0].tileMap, [[1]]);
assert.deepEqual(result.value.backgrounds[0].autoTileMap, [[2]]);
assert.equal(hasAssetReferenceWarning(result.value.backgrounds[1], 'backgroundId'), false);
assert.equal(countAssetReferenceAttention(result.value), 2);
assert.equal(countSceneAttention(result.value), 2);
assert.equal(clearMissingAssetReferences(result.value, available).changed, false);
const repaired = { ...result.value, backgrounds: result.value.backgrounds.map(layer => ({ ...layer, backgroundId: 'valid-bg' })), actors: result.value.actors.map(actor => ({ ...actor, spriteId: 'valid-sprite' })) };
assert.equal(countSceneAttention(repaired), 0);
const prefab = clearMissingAssetReferences({ type: 'actor', actor: { spriteId: 'deleted-sprite' } }, available).value;
assert.equal(countPrefabAttention(prefab), 1);
const settings = clearMissingAssetReferences({ playerSpriteId: 'deleted-sprite', shooterConfig: { projectileSpriteId: 'deleted-sprite' } }, available).value;
assert.equal(countAssetReferenceAttention(settings), 2);
const event = { command: 'EVENT_CHANGE_LAYER', args: { backgroundId: 'deleted-bg' } };
const events = clearMissingEventReferences(event, { ...available, scenes: new Set(), actors: new Set(), triggers: new Set(), scripts: new Set(), variables: new Set() });
assert.equal(events.changed, true);
assert.equal(events.value.args.backgroundId, undefined);
assert.ok(events.value.args.__referenceWarnings.backgroundId);
assert.equal(clearMissingAssetReferences({ spriteId: 'valid-sprite', backgroundId: 'valid-bg' }, available).changed, false);
const legacyScene = { _resourceType: 'scene', backgroundId: null, __referenceWarnings: { backgroundId: 'Removed legacy background' }, backgrounds: [{ layerId: 2, backgroundId: 'valid-bg' }], actors: [], script: [] };
assert.equal(countSceneAttention(legacyScene), 0, 'Deprecated scene.backgroundId must not produce an unlocatable warning');
const migrated = clearMissingAssetReferences(legacyScene, available);
assert.equal(migrated.changed, true);
assert.equal(migrated.value.__referenceWarnings, undefined);
assert.equal(Object.hasOwn(migrated.value, 'backgroundId'), false, 'Legacy slot is removed, not merely hidden');
assert.equal(legacyScene.__referenceWarnings.backgroundId, 'Removed legacy background', 'Cleanup remains immutable');
assert.equal(migrated.value.backgrounds, legacyScene.backgrounds, 'Valid layer references remain unchanged');
assert.equal(clearMissingAssetReferences(migrated.value, available).changed, false);
const missingLayer = { ...legacyScene, backgrounds: [{ layerId: 2, backgroundId: null, __referenceWarnings: { backgroundId: 'Missing layer background' } }] };
assert.equal(countSceneAttention(missingLayer), 1, 'The real layer warning is still counted');
assert.equal(countSceneAttention(clearMissingAssetReferences(missingLayer, available).value), 1);
const references = { ...legacyScene, id: 'scene-uuid', backgroundId: 'obsolete-uuid', __referenceWarnings: { backgroundId: 'Old warning', otherField: 'Keep warning' }, script: [{ command: 'EVENT_CHANGE_LAYER', args: { backgroundId: 'event-bg-uuid' } }] };
const normalized = normalizeSceneResource(references);
assert.equal(normalized.id, references.id);
assert.equal(normalized.backgrounds, references.backgrounds);
assert.equal(normalized.script, references.script);
assert.deepEqual(normalized.__referenceWarnings, { otherField: 'Keep warning' });
assert.equal(JSON.parse(JSON.stringify(normalized)).script[0].args.backgroundId, 'event-bg-uuid');
assert.equal(normalizeSceneResource(normalized), normalized, 'Migration is idempotent');
const standaloneEvent = { command: 'EVENT_CHANGE_LAYER', args: { backgroundId: 'event-bg-uuid' } };
assert.equal(normalizeSceneResource(standaloneEvent), standaloneEvent);
assert.equal(references.backgroundId, 'obsolete-uuid', 'Input data remains immutable');
console.log('Asset references: layers, actors, prefabs, settings, events, alerts and replacement passed.');
