const catalogs: Record<AppLanguage, TranslationCatalog> = {
  en_US: enUS,
  es_ES: esES,
  fr_FR: frFR,
  pt_BR: ptBR,
};

export function resolveLanguage(language?: string): AppLanguage {
  if (language && language !== 'systemDefault' && language in catalogs) {
    return language as AppLanguage;
  }
  const systemLanguage = (navigator.language || 'en-US').replace('-', '_');
  if (systemLanguage.startsWith('pt')) return 'pt_BR';
  if (systemLanguage.startsWith('es')) return 'es_ES';
  if (systemLanguage.startsWith('fr')) return 'fr_FR';
  return 'en_US';
}

interface I18nContextValue {
  language: AppLanguage;
  t: (key: string, params?: TranslationParams) => string;
}

const I18nContext = createContext<I18nContextValue>({ language: 'en_US', t: key => key });

export function I18nProvider({ language, children }: { language: AppLanguage; children: ReactNode }) {
  const value = useMemo<I18nContextValue>(() => ({
    language,
    t: (key, params) => {
      const template = catalogs[language][key] ?? catalogs.en_US[key] ?? key;
      return Object.entries(params ?? {}).reduce(
        (text, [name, replacement]) => text.replaceAll(`{${name}}`, String(replacement)),
        template,
      );
    },
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
