/** Creates the 42 deterministic GBA style starter sounds shown in the instrument bank. */
export function createLegacyTrackerStarterInstrumentBank(length = 2048, sustainLoops = true): TrackerStarterInstrumentDefinition[] {
  if (!Number.isInteger(length) || length < 64 || length > 65_535) throw new Error('Starter instrument length must be between 64 and 65535 frames.');
  const entries: TrackerStarterInstrumentDefinition[] = [];
  for (const category of ['Duty', 'Wave', 'Noise'] as const) {
    STARTER_INSTRUMENT_NAMES[category].forEach((name, presetIndex) => {
      const pcm = new Uint8Array(length);
      const sustainStart = Math.max(0, Math.floor(length / 64) * 64 - 64);
      const sustainedEnvelope = sustainLoops && category === 'Duty' && presetIndex <= 2;
      const oneShot = category === 'Noise' || (sustainLoops && category === 'Duty' && (presetIndex >= 3 && presetIndex <= 5 || presetIndex === 10));
      let random = (0x6d2b79f5 ^ (presetIndex + 1) * (category === 'Duty' ? 0x1f123bb5 : category === 'Wave' ? 0x45d9f3b : 0x119de1f3)) >>> 0;
      const widths = category === 'Duty' ? [0.25, 0.5, 0.125, 0.125, 0.25, 0.5, 0.125, 0.25, 0.5, 0.75, 0.5, 0.5, 0.125, 0.25] : [0.125, 0.25, 0.3125, 0.375, 0.4375, 0.5, 0.5, 0.5, 0.5];
      const width = widths[presetIndex] ?? 0.5;
      for (let frame = 0; frame < length; frame += 1) {
        const progress = (sustainedEnvelope ? Math.min(frame, sustainStart) : frame) / length;
        const phase = (frame % 64) / 64;
        let value = 0;
        if (category === 'Noise') {
          random ^= random << 13; random ^= random >>> 17; random ^= random << 5;
          const noise = ((random >>> 0) / 0xffffffff) * 2 - 1;
          const bassDrum = presetIndex === 10 || presetIndex === 11;
          const snare = presetIndex >= 6 && presetIndex <= 8;
          const metallic = presetIndex === 9;
          const envelope = bassDrum ? Math.exp(-progress * 12) : presetIndex <= 2 ? Math.exp(-progress * 20) : Math.exp(-progress * (presetIndex === 3 ? 4 : 7));
          const tone = Math.sin(phase * Math.PI * 2 * (bassDrum ? 2 + (1 - progress) * 12 : metallic ? 11 : snare ? 5 : 1));
          value = (bassDrum ? tone * 0.88 + noise * 0.12 : snare ? noise * 0.72 + tone * 0.28 : noise) * envelope;
        } else {
          let adjustedPhase = (phase + (category === 'Duty' && presetIndex === 9 ? Math.sin(progress * Math.PI * 8) * 0.025 : 0)) % 1;
          let wave: number;
          if (category === 'Wave' && presetIndex === 10) wave = 1 - 4 * Math.abs(adjustedPhase - 0.5);
          else if (category === 'Wave' && presetIndex === 12) wave = adjustedPhase * 2 - 1;
          else if (category === 'Wave' && presetIndex === 13) wave = Math.sign(adjustedPhase * 2 - 1) * Math.min(1, Math.abs(adjustedPhase * 2 - 1) * 2.6);
          else if ((category === 'Wave' && presetIndex >= 9 && presetIndex <= 11)) {
            const base = category === 'Wave' && presetIndex === 11 ? 1 - 4 * Math.abs(adjustedPhase - 0.5) : Math.sign(adjustedPhase - 0.5);
            wave = (base + Math.sign(((frame * 4) % 64) / 64 - 0.5) * 0.24) / 1.24;
          } else wave = adjustedPhase < width ? 1 : -1;
          let envelope = 1;
          if (category === 'Duty' && presetIndex === 0) envelope = Math.max(0.12, 1 - progress * 0.75);
          if (category === 'Duty' && presetIndex === 1) envelope = Math.max(0.12, 1 - progress * 0.5);
          if (category === 'Duty' && presetIndex === 2) envelope = Math.min(1, progress * 8 + 0.12);
          if (category === 'Duty' && presetIndex >= 3 && presetIndex <= 5) envelope = Math.min(1, Math.sin(Math.min(1, progress * (presetIndex === 3 ? 2 : presetIndex === 4 ? 3 : 4)) * Math.PI));
          if (category === 'Duty' && presetIndex === 10) envelope = Math.exp(-progress * 8);
          if (category === 'Wave' && presetIndex >= 6 && presetIndex <= 8) envelope = [0.78, 0.48, 0.2][presetIndex - 6];
          value = wave * envelope * (category === 'Wave' ? 0.72 : 0.84);
        }
        const signed = Math.max(-127, Math.min(127, Math.round(value * 120)));
        pcm[frame] = signed & 0xff;
      }
      entries.push({ name, category, color: STARTER_INSTRUMENT_COLORS[presetIndex], pcm, loop: !oneShot,
        loopStart: sustainedEnvelope ? sustainStart : 0, loopEnd: oneShot ? 0 : Math.floor(length / 64) * 64 });
    });
  }
  return entries;
}

/** Returns deterministic signed 8-bit mono PCM at the GBA Tracker starter rate. */
export function createLegacyTrackerInstrumentPresetPcm(presetId: TrackerInstrumentPresetId, length = TRACKER_INSTRUMENT_PRESETS.find(preset => preset.id === presetId)?.sampleLength ?? 2048): Uint8Array {
  if (!Number.isInteger(length) || length < 1 || length > 65_535) throw new Error('Instrument preset length must be between 1 and 65535 frames.');
  if (!TRACKER_INSTRUMENT_PRESETS.some(preset => preset.id === presetId)) throw new Error(`Unknown tracker instrument preset: ${String(presetId)}`);
  const result = new Uint8Array(length);
  let random = 0x6d2b79f5;
  let drumPhase = 0;
  for (let frame = 0; frame < length; frame += 1) {
    const phase = (frame % 64) / 64;
    let value: number;
    if (presetId === 'sine-lead') value = Math.sin(phase * Math.PI * 2) * 92;
    else if (presetId === 'pulse-lead') value = (phase < 0.375 ? 1 : -1) * 76;
    else if (presetId === 'triangle-bass') value = (1 - 4 * Math.abs(phase - 0.5)) * 100;
    else if (presetId === 'noise-hit') {
      random ^= random << 13; random ^= random >>> 17; random ^= random << 5;
      const envelope = Math.max(0, 1 - frame / length);
      value = (((random >>> 0) / 0xffffffff) * 2 - 1) * 104 * envelope;
    } else {
      random ^= random << 13; random ^= random >>> 17; random ^= random << 5;
      const noise = ((random >>> 0) / 0xffffffff) * 2 - 1;
      const time = frame / 8363;
      const angle = phase * Math.PI * 2;
      const attack = Math.min(1, frame / 24);
      const release = Math.min(1, (length - 1 - frame) / 128);
      if (presetId === 'electric-guitar') {
        const string = Math.sin(angle) + 0.48 * Math.sin(angle * 2) * Math.exp(-time * 4) + 0.25 * Math.sin(angle * 3) * Math.exp(-time * 8);
        value = Math.tanh(string * 2) * Math.exp(-time * 2.8) * attack * release * 100;
      } else if (presetId === 'acoustic-guitar') {
        const string = Math.sin(angle) * Math.exp(-time * 2.5) + 0.5 * Math.sin(angle * 2) * Math.exp(-time * 5) + 0.3 * Math.sin(angle * 3) * Math.exp(-time * 8) + noise * Math.exp(-time * 80) * 0.12;
        value = string * attack * release * 68;
      } else if (presetId === 'keyboard') {
        const body = Math.sin(angle) * Math.exp(-time * 2.4) + 0.42 * Math.sin(angle * 2) * Math.exp(-time * 5) + 0.18 * Math.sin(angle * 4) * Math.exp(-time * 10);
        value = body * attack * release * 75;
      } else if (presetId === 'saxophone') {
        const reed = Math.sin(angle) + 0.45 * Math.sin(angle * 2) + 0.24 * Math.sin(angle * 3) + 0.12 * Math.sin(angle * 4);
        value = Math.tanh(reed * 1.4) * Math.min(1, frame / 64) * 96;
      } else if (presetId === 'violin') {
        const bowed = Math.sin(angle) + 0.42 * Math.sin(angle * 2) + 0.3 * Math.sin(angle * 3)
          + 0.18 * Math.sin(angle * 4) + 0.12 * Math.sin(angle * 5) + 0.08 * Math.sin(angle * 6);
        const bowAttack = (1 - Math.cos(Math.PI * Math.min(1, frame / 768))) / 2;
        value = bowed * bowAttack * 68;
      } else if (presetId === 'kick-drum') {
        drumPhase += 2 * Math.PI * (48 + 150 * Math.exp(-time * 35)) / 8363;
        value = (Math.sin(drumPhase) * Math.exp(-time * 16) + noise * Math.exp(-time * 150) * 0.12) * attack * release * 110;
      } else if (presetId === 'snare-drum') {
        value = (noise * 0.75 + Math.sin(2 * Math.PI * 180 * time) * 0.25) * Math.exp(-time * 22) * attack * release * 110;
      } else {
        const metal = Math.sin(angle * 11) * Math.sin(angle * 17);
        value = (noise * 0.65 + metal * 0.35) * Math.exp(-time * 45) * attack * release * 85;
      }
    }
    const signed = Math.max(-127, Math.min(127, Math.round(value)));
    result[frame] = signed & 0xff;
  }
  return result;
}
