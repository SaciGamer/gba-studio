export function getEventLabel(command: string, t: (key: string) => string): string {
  const keys: Record<string, string> = {
    [EEvents.ACTOR_SET_STATE]: 'events.EVENT_ACTOR_SET_STATE',
    [EEvents.UI_DESTROY]: 'events.ui.destroy',
    [EEvents.UI_HIDE]: 'events.ui.hide',
    [EEvents.UI_SHOW]: 'events.ui.show',
  };
  const key = keys[command];
  const translated = key ? t(key) : undefined;
  return translated && translated !== key ? translated : EVENT_INFO[command as EEvents]?.name ?? command;
}
